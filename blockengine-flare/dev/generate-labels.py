"""Regenerate the inspector's static bitmap font and labels; no Flare internals are imported."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
glyphs = {}
for line in (root / "dev/font.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    code, *rows = line.split()
    glyphs[int(code)] = sum(int(row, 16) << (5 * index) for index, row in enumerate(rows))

values = []
for code in range(32, 128):
    glyph = glyphs.get(ord(chr(code).upper()), glyphs[63])
    values.append(f"uvec2(0x{glyph & 0xffffffff:08X}u, 0x{glyph >> 32:08X}u)")

labels = [
    "BLOCKENGINE / WAND INSPECTOR", "LIVE SERVER SNAPSHOT", "KIND",
    "BLOCK", "STATE", "BACKING", "WORLD", "X", "Y", "Z",
    "CHUNK X             Z", "DISPLAYS            EXPOSED",
    "PAYLOAD BYTES", "HARDNESS", "MINING SPEED", "UNBREAKABLE",
    "", "~ = NAME TRUNCATED / N/A = NOT CUSTOM", "/BEINSPECTOR FOR FULL DEBUG AND SETTINGS",
]
text = ", ".join(str(ord(char)) for line in labels for char in line.ljust(44))
font = """// Generated by dev/generate-labels.py from the add-on's own font.txt.
#ifndef BLOCKENGINE_INSPECTOR_TEXT
#define BLOCKENGINE_INSPECTOR_TEXT
const uvec2 GLYPHS[96] = uvec2[96](
    %s
);
bool glyph(int code, ivec2 cell) {
    if (code < 32 || code > 127 || cell.x < 0 || cell.x >= 5 || cell.y < 0 || cell.y >= 7) return false;
    int bit = cell.y * 5 + 4 - cell.x;
    return ((GLYPHS[code - 32][bit / 32] >> uint(bit %% 32)) & 1u) != 0u;
}
const int LABELS[%d] = int[%d](%s);
int label(int row, int column) {
    if (row < 0 || row >= %d || column < 0 || column >= 44) return 32;
    return LABELS[row * 44 + column];
}
#endif
""" % (",\n    ".join(values), len(labels) * 44, len(labels) * 44, text, len(labels))
target = root / "pack/assets/blockengine_inspector/shaders/include/text.glsl"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(font, encoding="utf-8", newline="\n")
